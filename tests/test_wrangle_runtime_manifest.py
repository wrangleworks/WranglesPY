def test_original_output_file_cli_and_artifact_bundle_have_identical_content(monkeypatch, tmp_path, capsys):
    manifest = exporter.build_manifest(source_revision="a" * 40)
    calls = []

    def export_checkout(**kwargs):
        calls.append(kwargs)
        return manifest

    monkeypatch.setattr(exporter, "export_checkout", export_checkout)
    legacy = tmp_path / "wrangle_runtime_manifest.json"
    exporter.main(["--output", str(legacy), "--source-revision", "a" * 40])
    file_summary = json.loads(capsys.readouterr().out)
    exporter.main(["--artifact-dir", str(tmp_path / "artifacts"), "--source-revision", "a" * 40])
    bundle_summary = json.loads(capsys.readouterr().out)
    content = (tmp_path / "artifacts" / exporter.FILENAME).read_bytes()
    assert legacy.read_bytes() == content
    assert file_summary["sha256"] == bundle_summary["sha256"]
    assert file_summary["source"] == bundle_summary["source"] == manifest["source"]
    assert calls == [{"tag": None, "expected_revision": "a" * 40, "allow_dirty": False}] * 2
    assert (tmp_path / "artifacts" / (exporter.FILENAME + ".sha256")).read_text().split()[0] == file_summary["sha256"]


def test_real_runtime_export_resolves_all_keys_without_service_calls(monkeypatch):
    import requests
    from wrangles import recipe, config, utils

    def forbidden(*args, **kwargs):
        pytest.fail("Export attempted a network request")

    monkeypatch.setattr(requests.sessions.Session, "request", forbidden)
    value = exporter.build_manifest(root=recipe._recipe_wrangles, config=config, source_version="1.20.4", source_revision=REVISION)
    entries = {entry["runtime_key"]: entry for entry in value["wrangles"]}
    assert {"lookup", "standardize", "standardize.clean", "standardize.custom", "try", "convert.parse", "math", "maths"} <= entries.keys()
    assert not any(key.startswith(("pandas.", "main.", "custom.")) for key in entries)
    for key, entry in entries.items():
        function = utils.get_nested_function(config.reserved_word_replacements.get(key, key), recipe._recipe_wrangles)
        assert entry["python_symbol"] == f"{function.__module__}.{function.__qualname__}"
        assert {parameter["name"] for parameter in entry["parameters"]} | set(entry["internal_parameters"]) | {
            name for name in entry["variadic"].values() if name is not None
        } == set(inspect.signature(function).parameters)
    sentinel = next(parameter for parameter in entries["convert.parse"]["parameters"] if parameter["name"] == "default")
    assert sentinel == {"name": "default", "kind": "positional_or_keyword", "required": False}
    assert "wrangles.recipe_wrangles.convert._DEFAULT_NOT_SET" in entries["convert.parse"]["signature"]


def test_exported_legacy_alias_still_executes_through_the_real_recipe_dispatcher():
    import pandas as pd
    from wrangles import recipe, config

    entries = {entry["runtime_key"]: entry for entry in
               exporter.build_manifest(root=recipe._recipe_wrangles, config=config, source_version="1.20.4", source_revision=REVISION)["wrangles"]}
    assert entries["math"]["parameters"] == entries["maths"]["parameters"]
    data = pd.DataFrame({"quantity": [2, 3, 0], "price": [5, 7, 8]})
    results = [recipe.run({"wrangles": [{key: {"input": "quantity * price", "output": "total"}}]},
                          dataframe=data.copy()) for key in ("math", "maths")]
    pd.testing.assert_frame_equal(results[0], results[1])
    assert results[0]["total"].tolist() == [10, 21, 0]


def test_docstrings_preserve_schema_or_plain_text_without_guessing():
    def plain(df):
        """Deprecated - use math"""

    entries = {entry["runtime_key"]: entry for entry in manifest(namespace(schema=operation, plain=plain))["wrangles"]}
    assert entries["schema"]["docstring_schema"] == {"type": "object", "properties": {"input": {"type": "string"}}}
    assert entries["schema"]["plain_docstring"] is None
    assert entries["plain"]["docstring_schema"] is None
    assert entries["plain"]["docstring_schema_status"] == "missing"
    assert entries["plain"]["plain_docstring"] == "Deprecated - use math"
    plain.__doc__ = "Notes: [literal brackets"
    assert manifest(namespace(plain=plain))["wrangles"][0]["plain_docstring"] == plain.__doc__
    plain.__doc__ = "type: [unfinished"
    with pytest.raises(ValueError, match="plain has an invalid JSON Schema docstring"):
        manifest(namespace(plain=plain))


