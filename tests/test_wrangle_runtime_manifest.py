def test_cli_exports_checkout_and_rejects_a_missing_source_tree(tmp_path):
    # The existing test-container job deliberately removes the source tree to
    # test the installed package and has no Git executable. Reject that input
    # before attempting to read its provenance.
    has_source = (exporter.ROOT / "wrangles/__init__.py").is_file()
    revision_args = []
    if has_source:
        revision = exporter.git(exporter.ROOT, "rev-parse", "HEAD")
        revision_args = ["--revision", revision]
    result = subprocess.run([sys.executable, str(exporter.ROOT / "schema/generate_wrangle_manifest.py"),
                             "--allow-dirty", *revision_args, "--artifact-dir", str(tmp_path)],
                            cwd=exporter.ROOT, capture_output=True, text=True)
    if not has_source:
        assert result.returncode == 1
        assert "has no WranglesPY source tree" in result.stderr
        assert not (tmp_path / exporter.FILENAME).exists()
        return
    assert result.returncode == 0, result.stderr
    summary = json.loads(result.stdout)
    value = json.loads((tmp_path / exporter.FILENAME).read_bytes())
    assert summary["source"] == value["source"]
    assert value["source"]["revision"] == revision
    assert value["source"]["repository"] == exporter.REPOSITORY
    assert summary["entry_count"] == len(value["wrangles"])
    assert summary["sha256"] == hashlib.sha256((tmp_path / exporter.FILENAME).read_bytes()).hexdigest()


def test_catalog_identity_survives_move_rename_and_legacy_execution():
    identity = "9223372036854775807"
    @catalog_identity(identity)
    def original(df, input):
        return input.upper()

    before = manifest(namespace(old=original))["wrangles"][0]
    original.__module__ = "wrangles.recipe_wrangles.moved"
    original.__qualname__ = "renamed"

    def old(df, input):
        return original(df, input)

    after = {entry["runtime_key"]: entry for entry in manifest(namespace(new=original, old=old))["wrangles"]}
    assert before["catalog_id"] == after["new"]["catalog_id"] == identity
    assert after["new"]["python_symbol"] == "wrangles.recipe_wrangles.moved.renamed"
    assert "catalog_id" not in after["old"]
    assert old(None, "bolt") == original(None, "bolt") == "BOLT"
    assert catalog_identity(identity)(original) is original
    with pytest.raises(ValueError, match="cannot be reassigned"):
        catalog_identity("2" if identity != "2" else "3")(original)


